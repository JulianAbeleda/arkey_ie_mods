#!/bin/bash
# build_stubs.sh STUBS SYMBOLS: the do-nothing CUDA runtime (cudastub.cpp) as the four libraries the engine build loads, under
# their SONAMEs and versioned like them, into STUBS/stublib. Every symbol of the SYMBOLS file (match_gate.sh: syms.txt and what the
# tree's libggml-cuda imports) cudastub.cpp does not define gets a do-nothing "return 0" (x86-64: extra arguments are ignored). Needs the CUDA headers (CUDA_INCLUDE, default /usr/local/cuda/include).
set -e; D=$(cd "$(dirname "$0")" && pwd); B=$1; SYMS=$(realpath $2); CU=${CUDA_INCLUDE:-/usr/local/cuda/include}
mkdir -p $B/stublib; cd $B
g++ -O1 -fPIC -c $D/cudastub.cpp -I$CU -o cudastub.o
nm --defined-only cudastub.o | awk '$2=="T"{print $3}' | sort > defined.txt
sed 's/@.*//' $SYMS | sort -u | comm -23 - defined.txt > default.txt
{ echo "/* generated by build_stubs.sh: do-nothing defaults */"; while read s; do echo "long $s(void) { return 0; }"; done < default.txt; } > cudastub_default.c
gcc -O1 -fPIC -c cudastub_default.c -o cudastub_default.o
for lib in libcudart.so.13 libcublas.so.13 libcublasLt.so.13 libcuda.so.1; do
  echo "$lib { global: *; };" > ver-$lib.map
  g++ -shared -o stublib/$lib cudastub.o cudastub_default.o -Wl,-soname,$lib -Wl,--version-script=ver-$lib.map
done
