// hook_gate: the MATCH step of the kernel lifecycle (propose -> check -> MATCH -> time -> gate -> install), on the CPU.
// Input: (a) graphs as the engine built and ALLOCATED them (hookspy's boltbeam.engine_graph_dump.v2: from a cudastub dry
// run of the unmodified engine build, or from one real GPU run), (b) a kernels manifest. It runs the engine's own matcher
// (ext-kernels.cpp of the named tree, included as source; the only change is mechanical: every `return {};` of ext_match
// records its source line and loop indices, see gate_build.sh) over every graph in the backend's node order, first
// matching entry wins, and reports per entry and graph kind (node count):
//   shape spots   positions whose N nodes have the entry's ops, types and shapes (what a search / bench counts)
//   matched       windows the matcher takes
//   refused       address refusals, with the pair, both byte ranges, exact alias or partial overlap, and where the
//                 input is last read in the stock order
//   rejected      for a spot that is not taken: the first rule (source line of ext_match) and node that rejected it
// With --check it also compares its result on every graph with what the ENGINE's matcher did on that same graph in the
// run that wrote the dump (the pass record): they must agree node for node, or the replay is not trusted.
// --steps TURNS.json (drive_session.py's record): the passes that are DECODE steps. An --expect is judged only there:
// windows of the entry taken in passes of the step graph kind (the largest graph evaluated inside the decode windows),
// divided by those passes. Without --steps no --expect can pass: a prompt pass that happens to have the entry's shape
// (region_state_copy_front matched a 10-token prompt pass and no decode step) must not count.
// --json writes the report (arkey.match_gate.v1) that BoltBeam's region search reads (its llama.cpp match adapter) before a kernel may be timed.
// usage: hook_gate SPY.jsonl MANIFEST.json [--check] [--steps TURNS.json] [--expect ID=N ...] [--json OUT.json]
