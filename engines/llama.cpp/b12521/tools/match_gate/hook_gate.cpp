static bool is_view_or_noop(const ggml_tensor * t) {   // = ggml_cuda_is_view_or_noop (ggml-cuda.cu): the node loop skips these
    return ggml_is_empty(t) || t->op == GGML_OP_RESHAPE || t->op == GGML_OP_TRANSPOSE || t->op == GGML_OP_VIEW || t->op == GGML_OP_PERMUTE || t->op == GGML_OP_NONE;
}
static std::string ne_str(const int64_t * ne) { char b[96]; snprintf(b, sizeof(b), "[%lld, %lld, %lld, %lld]", (long long) ne[0], (long long) ne[1], (long long) ne[2], (long long) ne[3]); return b; }
static std::string nb_str(const size_t * nb) { char b[96]; snprintf(b, sizeof(b), "[%zu, %zu, %zu, %zu]", nb[0], nb[1], nb[2], nb[3]); return b; }
static std::vector<std::string> g_src;   // the matcher's source lines, for naming a rule
static std::set<int> g_rules;             // rule lines that rejected something: printed once
static std::string rule_text(int line) {  // the if (...) that ends at this return
    int a = line - 1;
    while (a > 0 && g_src[a].find("if (") == std::string::npos) --a;
    std::string t;
    for (int q = a; q < line - 1 && q < (int) g_src.size(); ++q) { std::string l = g_src[q]; l.erase(0, l.find_first_not_of(" \t")); t += l + " "; }
    for (const char * junk : { " ext_gate_k = k; ext_gate_s = -1;", " ext_gate_s = (int) s;", " ext_gate_o = o;" }) for (size_t p; (p = t.find(junk)) != std::string::npos;) t.erase(p, strlen(junk));
    return t;
}
// the shipped matcher's ext_op has no strides (every node contiguous); the next one has
template <class O> static auto op_nb(const O & o, int) -> decltype(o.nb) { return o.nb; }
template <class O> static std::vector<size_t> op_nb(const O &, long) { return {}; }
// which sub-test of the per-op rule failed (explanation only: the verdict is the matcher's)
static std::string explain_op(const ext_op & op, const ggml_tensor * t, int k) {
    char b[512]; const std::vector<size_t> onb = op_nb(op, 0);
    if (t->op != op.op) { snprintf(b, sizeof(b), "op %d: graph has %s, entry %s", k, ggml_op_name(t->op), ggml_op_name(op.op)); return b; }
    if (t->type != op.type) { snprintf(b, sizeof(b), "op %d (%s): type %s, entry %s", k, ggml_op_name(t->op), ggml_type_name(t->type), ggml_type_name(op.type)); return b; }
    if (memcmp(t->ne, op.ne.data(), sizeof(t->ne)) != 0) { snprintf(b, sizeof(b), "op %d (%s): shape %s, entry %s", k, ggml_op_name(t->op), ne_str(t->ne).c_str(), ne_str(op.ne.data()).c_str()); return b; }
    if (onb.empty() ? !ggml_is_contiguous(t) : memcmp(t->nb, onb.data(), sizeof(t->nb)) != 0) { snprintf(b, sizeof(b), "op %d (%s): strides %s, entry %s", k, ggml_op_name(t->op), nb_str(t->nb).c_str(), onb.empty() ? "contiguous" : nb_str(onb.data()).c_str()); return b; }
    if ((uintptr_t) t->data % (onb.empty() ? 16 : ggml_type_size(op.type)) != 0) { snprintf(b, sizeof(b), "op %d (%s): data address %p not aligned", k, ggml_op_name(t->op), t->data); return b; }
    if (op.unary >= 0 && (int) ggml_get_unary_op(t) != op.unary) { snprintf(b, sizeof(b), "op %d: another unary op", k); return b; }
    if (k > 0 && (t->flags & GGML_TENSOR_FLAG_COMPUTE) == 0) { snprintf(b, sizeof(b), "op %d (%s): node not flagged COMPUTE", k, ggml_op_name(t->op)); return b; }
    if (!op.params.empty() && memcmp(t->op_params, op.params.data(), op.params.size() * sizeof(float)) != 0) {
        std::string g, e2; for (size_t q = 0; q < op.params.size(); ++q) { char c[32]; snprintf(c, sizeof(c), "%g ", ((const float *) t->op_params)[q]); g += c; snprintf(c, sizeof(c), "%g ", op.params[q]); e2 += c; }
        snprintf(b, sizeof(b), "op %d (%s): op_params %s, entry %s", k, ggml_op_name(t->op), g.c_str(), e2.c_str()); return b;
    }
    snprintf(b, sizeof(b), "op %d (%s): per-op rule", k, ggml_op_name(t->op)); return b;
}
struct graph_data { long gid; int n_nodes; std::string kind; std::vector<ggml_tensor> T; ggml_context * ctx; ggml_cgraph * gf; };
static std::string kind_of(int n_nodes, const int64_t * ne) { char b[128]; snprintf(b, sizeof(b), "%5d nodes, result %s", n_nodes, ne_str(ne).c_str()); return b; }
static graph_data load_graph(const json & j) {
    graph_data g; g.gid = j.at("graph").get<long>(); g.n_nodes = j.at("n_nodes").get<int>();
    const json & ts = j.at("tensors");
    g.T.assign(ts.size(), ggml_tensor{});
    for (size_t q = 0; q < ts.size(); ++q) {
        const json & t = ts[q]; ggml_tensor & x = g.T[q];
        x.op = (ggml_op) t.at("opi").get<int>(); x.type = (ggml_type) t.at("typei").get<int>(); x.flags = t.at("flags").get<int32_t>();
        if (std::string(ggml_op_name(x.op)) != t.at("op").get<std::string>() || std::string(ggml_type_name(x.type)) != t.at("type").get<std::string>()) {
            throw std::runtime_error("the dump's op / type numbers are not this tree's: build the gate from the tree that wrote the dump");
        }
        for (int d = 0; d < GGML_MAX_DIMS; ++d) { x.ne[d] = t.at("ne")[d].get<int64_t>(); x.nb[d] = t.at("nb")[d].get<size_t>(); }
        x.data = (void *) (uintptr_t) t.at("data").get<uint64_t>(); x.view_offs = t.at("view_offs").get<size_t>();
        const int vs = t.at("view_src").get<int>(); x.view_src = vs >= 0 ? &g.T[vs] : nullptr;
        int s = 0; for (const json & id : t.at("src")) x.src[s++] = &g.T[id.get<int>()];
        const std::string p = t.at("params").get<std::string>(), nm = t.at("name").get<std::string>();
        for (size_t d = 0; d + 1 < p.size() && d / 2 < sizeof(x.op_params); d += 2) ((unsigned char *) x.op_params)[d / 2] = (unsigned char) strtoul(p.substr(d, 2).c_str(), nullptr, 16);
        snprintf(x.name, sizeof(x.name), "%s", nm.c_str());
    }
    g.ctx = ggml_init({ ggml_graph_overhead_custom(g.n_nodes + 8, false) + (1 << 20), nullptr, true });
    g.gf  = ggml_new_graph_custom(g.ctx, g.n_nodes + 8, false);
    for (int i = 0; i < g.n_nodes; ++i) {
        g.gf->nodes[i] = &g.T[i];
        g.gf->use_counts[ggml_hash_find_or_insert(&g.gf->visited_hash_set, &g.T[i])] = ts[i].at("uses").get<int32_t>();
    }
    g.gf->n_nodes = g.n_nodes; g.kind = kind_of(g.n_nodes, g.T[g.n_nodes - 1].ne);
    return g;
}
struct entry_stats {
    long spots = 0, matched = 0, refused = 0, seq_spots = 0;
    std::map<std::string, long> why;        // rejected shape spots: rule -> count
    std::map<std::string, long> why_seq;    // op-sequence spots that are not shape spots: first difference -> count
    std::map<std::string, long> refusal;    // refusal description -> count
    std::string first_refusal, first_reject;
};
int main(int argc, char ** argv) {
    if (argc < 3) { fprintf(stderr, "usage: hook_gate SPY.jsonl MANIFEST.json [--check] [--steps TURNS.json] [--expect ID=N ...] [--json OUT.json]\n"); return 2; }
    const std::string spy = argv[1], man = argv[2], mdir = man.substr(0, man.find_last_of('/') + 1);
    bool check = false; std::map<std::string, double> expect; std::string json_out, steps_path;
    for (int a = 3; a < argc; ++a) {
        const std::string s = argv[a];
        if (s == "--check") check = true;
        else if (s == "--expect" && a + 1 < argc) { const std::string e = argv[++a]; expect[e.substr(0, e.find('='))] = atof(e.substr(e.find('=') + 1).c_str()); }
        else if (s == "--json" && a + 1 < argc) json_out = argv[++a];
        else if (s == "--steps" && a + 1 < argc) steps_path = argv[++a];
    }
    { std::ifstream f(GATE_SRC); for (std::string l; std::getline(f, l);) g_src.push_back(l); }
    ggml_log_set([](ggml_log_level, const char *, void *) {}, nullptr);   // the matcher's own refusal line: counted here instead
    std::string man_blob; { std::ifstream f(man, std::ios::binary); man_blob.assign((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>()); }
    const json m = json::parse(man_blob);
    std::vector<std::pair<long, long>> windows;   // decode windows [first, end) in pass numbers
    if (!steps_path.empty()) for (const json & r : json::parse(std::ifstream(steps_path))) if (r.contains("decode_passes")) windows.emplace_back(r["decode_passes"][0].get<long>(), r["decode_passes"][1].get<long>());
    json entries_json = json::array();
    const bool v2 = m.at("schema") == "boltbeam.kernel_manifest.v2";
    std::vector<ext_entry> entries;
    printf("hook_gate: matcher %s\nmanifest %s\n", GATE_SRC, man.c_str());
    for (const json & j : m.at("entries")) {
        try { entries.push_back(ext_load_entry(j, mdir, j.at("target").get<std::string>(), v2));
              entries_json.push_back({{"id", j.at("id")}, {"kernel_sha256", j.at("kernel").at("sha256")}, {"placeholder", j.at("kernel").value("placeholder", false)}, {"ops", j.at("match").at("ops").size()}}); }
        catch (const std::exception & err) { printf("  entry %s DROPPED at load: %s\n", j.value("id", "?").c_str(), err.what()); }
    }
    // pass records: every evaluation of the run, by graph kind; what the engine's own matcher took (and, in a dry run, which kernel)
    std::map<long, std::vector<std::pair<int, int>>> engine_hits; std::map<std::string, long> evals; std::map<std::string, std::map<std::string, long>> engine_by;
    std::map<std::string, std::map<std::string, std::pair<long, long>>> engine_minmax; bool have_by = false;
    std::map<std::string, long> dec_evals; std::map<std::string, int> dec_nodes; std::map<std::string, std::map<std::string, long>> dec_by;
    {
        std::ifstream f(spy);
        for (std::string l; std::getline(f, l);) {
            if (l.compare(0, 7, "{\"pass\"") != 0) continue;
            const json p = json::parse(l); const long gid = p.at("gid").get<long>();
            int64_t ne[4]; for (int d = 0; d < 4; ++d) ne[d] = p.at("last_ne")[d].get<int64_t>();
            const std::string kind = kind_of(p.at("n_nodes").get<int>(), ne);
            evals[kind]++;
            const long pn = p.at("pass").get<long>(); bool in_win = false;
            for (auto & [a, b] : windows) in_win = in_win || (pn >= a && pn < b);
            if (in_win) { dec_evals[kind]++; dec_nodes[kind] = p.at("n_nodes").get<int>(); for (auto & [sym, c] : p.at("by").items()) dec_by[kind][sym] += c.get<long>(); }
            for (auto & [sym, c] : p.at("by").items()) { engine_by[kind][sym] += c.get<long>(); have_by = true; }
            for (const ext_entry & e : entries) {   // per evaluation: fewest / most windows of each kernel (a count that moves from step to step is an address effect)
                const long c = p.at("by").value(e.id, 0L); auto it = engine_minmax[kind].find(e.id);
                if (it == engine_minmax[kind].end()) engine_minmax[kind][e.id] = { c, c }; else { it->second.first = std::min(it->second.first, c); it->second.second = std::max(it->second.second, c); }
            }
            std::vector<std::pair<int, int>> h; for (const json & x : p.at("hits")) h.emplace_back(x[0].get<int>(), x[1].get<int>());
            engine_hits[gid] = h;
        }
    }
    std::map<std::string, std::vector<entry_stats>> stats;   // graph kind -> per entry
    std::map<std::string, long> graphs_by_size; long n_graphs = 0, n_disagree = 0, n_checked = 0;
    std::ifstream f(spy);
    for (std::string l; std::getline(f, l);) {
        if (l.compare(0, 8, "{\"graph\"") != 0) continue;
        graph_data g = load_graph(json::parse(l));
        n_graphs++; graphs_by_size[g.kind]++;
        std::vector<entry_stats> & st = stats[g.kind]; st.resize(entries.size());
        std::vector<std::pair<int, int>> hits;
        std::vector<int> last_read(g.T.size(), -1);    // per tensor: the last node that reads it (itself or through a view chain)
        for (int i = 0; i < g.n_nodes; ++i) for (int s = 0; s < GGML_MAX_SRC && g.T[i].src[s]; ++s) for (const ggml_tensor * x = g.T[i].src[s]; x; x = x->view_src) last_read[x - g.T.data()] = i;
        for (int i = 0; i < g.n_nodes; ++i) {
            ggml_tensor * node = g.gf->nodes[i];
            if (is_view_or_noop(node) || (node->flags & GGML_TENSOR_FLAG_COMPUTE) == 0) continue;
            for (size_t q = 0; q < entries.size(); ++q) {
                ext_entry & e = entries[q]; const int n = (int) e.ops.size();
                bool seq = i + n <= g.n_nodes, shape = seq; int kdiff = -1;
                for (int k = 0; k < n && seq; ++k) {
                    const ggml_tensor * t = g.gf->nodes[i + k]; const ext_op & op = e.ops[k];
                    seq = t->op == op.op && (op.unary < 0 || (int) ggml_get_unary_op(t) == op.unary);
                    if (shape && !(t->type == op.type && memcmp(t->ne, op.ne.data(), sizeof(t->ne)) == 0)) { shape = false; kdiff = k; }
                }
                shape = shape && seq;
                g_rej = {}; g_refused = false; ext_gate_k = ext_gate_s = ext_gate_o = -1;
                const std::vector<ggml_tensor *> w = ext_match(e, g.gf, i);
                if (n > 1 && seq) st[q].seq_spots++;
                if (shape) st[q].spots++;
                if (!w.empty()) { st[q].matched++; hits.emplace_back(i, n); i += n - 1; break; }
                if (g_refused) {
                    st[q].refused++;
                    const ggml_tensor * out = g.gf->nodes[i + g_ref.o], * x = g.gf->nodes[i + g_ref.k]->src[g_ref.s];
                    const bool exact = g_ref.a0 == g_ref.b0 && g_ref.a1 == g_ref.b1;
                    const int  lr = last_read[x - g.T.data()], xi = (int) (x - g.T.data());
                    char b[700];
                    snprintf(b, sizeof(b), "output %d (%s %s %s, %zu bytes) %s input (%d, %d) (%s %s %s, %zu bytes)%s; input is %s, last read by node +%d of the window (%s); the output node is +%d",
                             g_ref.o, ggml_op_name(out->op), ggml_type_name(out->type), ne_str(out->ne).c_str(), (size_t) (g_ref.a1 - g_ref.a0),
                             exact ? "EXACT ALIAS of" : "PARTIAL OVERLAP with", g_ref.k, g_ref.s, ggml_op_name(x->op), ggml_type_name(x->type), ne_str(x->ne).c_str(), (size_t) (g_ref.b1 - g_ref.b0),
                             exact ? "" : " (ranges differ)", xi < g.n_nodes ? "a graph node" : "a leaf", lr - i, lr >= 0 ? ggml_op_name(g.gf->nodes[lr]->op) : "?", g_ref.o);
                    st[q].refusal[b]++;
                    if (st[q].first_refusal.empty()) { char c[900]; snprintf(c, sizeof(c), "graph %ld node %d: %s; output [%p, %p) input [%p, %p)", g.gid, i, b, g_ref.a0, g_ref.a1, g_ref.b0, g_ref.b1); st[q].first_refusal = c; }
                } else if (shape || (n > 1 && seq)) {
                    std::string why;
                    if (g_rej.k >= 0 && rule_text(g_rej.line).find("node->op != op.op") != std::string::npos) why = explain_op(e.ops[g_rej.k], g.gf->nodes[i + g_rej.k], g_rej.k);
                    g_rules.insert(g_rej.line);
                    char b[900]; snprintf(b, sizeof(b), "rule L%d%s%s%s%s%s", g_rej.line, g_rej.k >= 0 ? (" at op " + std::to_string(g_rej.k)).c_str() : "", g_rej.s >= 0 ? (" src " + std::to_string(g_rej.s)).c_str() : "",
                                          g_rej.o >= 0 ? (" output " + std::to_string(g_rej.o)).c_str() : "", why.empty() ? "" : ": ", why.c_str());
                    (shape ? st[q].why : st[q].why_seq)[b]++;
                    if (st[q].first_reject.empty()) st[q].first_reject = "graph " + std::to_string(g.gid) + " node " + std::to_string(i) + ": " + b;
                }
            }
        }
        if (check && engine_hits.count(g.gid)) {
            n_checked++;
            if (engine_hits[g.gid] != hits) { n_disagree++; printf("  DISAGREE graph %ld (%d nodes): engine took %zu windows, replay %zu\n", g.gid, g.n_nodes, engine_hits[g.gid].size(), hits.size()); }
        }
        ggml_free(g.ctx);
    }
    printf("stored graphs replayed: %ld. Per kind the run evaluated / stored:", n_graphs); for (auto & [k, c] : evals) printf("\n  %s: %ld evaluations, %ld stored", k.c_str(), c, graphs_by_size.count(k) ? graphs_by_size[k] : 0L); printf("\n");
    if (check) printf("check against the engine's own matcher on the same graphs: %ld graphs compared, %ld disagree%s\n", n_checked, n_disagree, n_disagree ? "  <-- REPLAY NOT TRUSTED" : "");
    json out = json::array(); int rc = n_disagree ? 3 : 0;
    for (auto & [kind, st] : stats) {
        const double d = (double) graphs_by_size[kind], ev = (double) evals[kind];
        bool any = false; for (size_t q = 0; q < entries.size(); ++q) any = any || st[q].spots > 0 || st[q].matched > 0;
        if (!any) continue;   // no entry has a shape spot in this kind
        printf("\n== %s: %ld evaluations in the run, %ld stored graphs\n", kind.c_str(), evals[kind], graphs_by_size[kind]);
        printf("  %-26s %4s | %-33s | %-48s\n", "", "", "ENGINE's matcher, all evaluations", "REPLAY, mean per stored graph (stored for novelty)");
        printf("  %-26s %4s | %12s %9s %9s | %11s %9s %9s %9s\n", "entry", "ops", "taken a pass", "min", "max", "shape spots", "matched", "refused", "rejected");
        for (size_t q = 0; q < entries.size(); ++q) {
            const entry_stats & x = st[q]; const std::string & id = entries[q].id;
            if (x.spots == 0 && x.matched == 0) continue;
            long rej = 0; for (auto & [w, c] : x.why) rej += c;
            if (have_by) printf("  %-26s %4zu | %12.2f %9ld %9ld | %11.2f %9.2f %9.2f %9.2f\n", id.c_str(), entries[q].ops.size(), engine_by[kind][id] / ev, engine_minmax[kind][id].first, engine_minmax[kind][id].second, x.spots / d, x.matched / d, x.refused / d, rej / d);
            else         printf("  %-26s %4zu | %12s %9s %9s | %11.2f %9.2f %9.2f %9.2f\n", id.c_str(), entries[q].ops.size(), "n/a", "", "", x.spots / d, x.matched / d, x.refused / d, rej / d);
            for (auto & [w, c] : x.refusal) printf("      refused x%ld: %s\n", c, w.c_str());
            if (!x.first_refusal.empty()) printf("      first refusal: %s\n", x.first_refusal.c_str());
            for (auto & [w, c] : x.why) printf("      shape spot rejected x%ld: %s\n", c, w.c_str());
            out.push_back({{"kind", kind}, {"entry", id}, {"evaluations", evals[kind]}, {"engine_taken", have_by ? json(engine_by[kind][id]) : json()}, {"stored_graphs", graphs_by_size[kind]}, {"shape_spots", x.spots},
                           {"matched", x.matched}, {"refused", x.refused}, {"refusals", x.refusal}, {"rejected", x.why}});
        }
    }
    // an entry with NO shape spot anywhere: say which rule turns its op-sequence spots away (a kernel built for a shape the run never has)
    for (size_t q = 0; q < entries.size(); ++q) {
        long spots = 0; for (auto & [kind, st] : stats) spots += st[q].spots + st[q].matched;
        if (spots > 0) continue;
        printf("\n== %s: NO shape spot in any stored graph of this run (0 matches). Where its op sequence does occur:\n", entries[q].id.c_str());
        for (auto & [kind, st] : stats) {
            if (st[q].seq_spots == 0) continue;
            printf("  %s: %.2f op-sequence spots a stored graph\n", kind.c_str(), st[q].seq_spots / (double) graphs_by_size[kind]);
            for (auto & [w, c] : st[q].why_seq) printf("      rejected x%ld: %s\n", c, w.c_str());
            out.push_back({{"kind", kind}, {"entry", entries[q].id}, {"seq_spots", st[q].seq_spots}, {"shape_spots", 0}, {"matched", 0}, {"rejected_other_shape", st[q].why_seq}});
        }
    }
    if (!g_rules.empty()) printf("\nrules (ext_match, %s):\n", GATE_SRC);
    for (int line : g_rules) printf("  L%d: %s\n", line, rule_text(line).c_str());
    // the decode step's graph kind: the largest graph evaluated inside the decode windows (the draft's graphs are smaller)
    std::string step_kind; long steps = 0;
    for (auto & [kind, n] : dec_evals) if (step_kind.empty() || dec_nodes[kind] > dec_nodes[step_kind]) { step_kind = kind; steps = n; }
    if (!windows.empty()) printf("\ndecode steps: %ld evaluations of [%s] inside %zu decode windows (%s)\n", steps, step_kind.c_str(), windows.size(), steps_path.c_str());
    json expects = json::array();
    for (auto & [id, want] : expect) {   // --expect ID=N: the entry's windows a DECODE step (engine's matcher, dry run), at least 90% of N
        const bool known = std::any_of(entries.begin(), entries.end(), [&](const ext_entry & e) { return e.id == id; });
        const bool judged = known && have_by && steps > 0;
        const double got = judged ? dec_by[step_kind][id] / (double) steps : 0.0;
        const bool ok = judged && got >= 0.9 * want;
        const char * why = !known ? "the entry did not load" : !have_by ? "the record has no per-kernel counts (not a dry run)" : steps == 0 ? "no decode windows (--steps): not a decode-shape report" : "";
        printf("EXPECT %s: %.2f taken a decode step, expected %.2f: %s%s%s\n", id.c_str(), got, want, ok ? "PASS" : "FAIL: do not spend GPU time", *why ? " - " : "", why);
        expects.push_back({{"id", id}, {"want", want}, {"got", got}, {"kind", step_kind}, {"decode_steps", steps}, {"pass", ok}});
        if (!ok) rc = 1;
    }
    if (!json_out.empty()) {
        const json rep = {{"schema", "arkey.match_gate.v1"}, {"matcher_source", GATE_SRC}, {"manifest", man}, {"manifest_sha256", ext_sha256(man_blob)}, {"spy", spy},
                          {"entries", entries_json}, {"check", {{"asked", check}, {"graphs", n_checked}, {"disagree", n_disagree}}},
                          {"decode", {{"windows", windows.size()}, {"step_kind", step_kind}, {"steps", steps}, {"per_kernel_counts", have_by}}},
                          {"expect", expects}, {"rows", out}, {"exit", rc}};
        std::ofstream(json_out) << rep.dump(1) << "\n";
    }
    return rc;
}
